import React, { useState } from 'react';
import { TeamTacticalProfile } from '../types/tactics';
import { Copy, Check, Printer, ShieldAlert, Award } from 'lucide-react';

interface ScoutingCardProps {
  team: TeamTacticalProfile;
}

export const ScoutingCard: React.FC<ScoutingCardProps> = ({ team }) => {
  const [copied, setCopied] = useState<boolean>(false);

  const handleCopy = () => {
    const text = `
=== TACTICAL SCOUTING BRIEF: ${team.name.toUpperCase()} ===
Tournament: ${team.tournament} | Matches Analyzed: ${team.matchesPlayed}
Total Turnovers: ${team.totalTurnovers} (${team.turnoversPerMatch}/match)
Defensive Third Turnovers: ${team.defensiveThirdTurnovers}
Conceded xG Post-Turnover: ${team.concededXgPostTurnover.toFixed(2)}
Squad Press Escape Rate: ${team.overallPressEscapeRate}%
Opponent Transition Window: ${team.avgTimeToConcededShotSec}s

TOP OPPOSITION PRESS TRIGGERS:
${team.tacticalTriggers.map((t, idx) => `
[TRIGGER ${idx + 1}] (${t.priority}) - ${t.title}
Target Sector: ${t.triggerZone} (Zone ${t.zoneId})
Target Player: ${t.targetPlayer}
Actionable Instruction: ${t.instruction}
Evidence: ${t.evidenceStat}
`).join('\n')}

Generated by TactixIQ Sports Analytics System.
`.trim();

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="bg-surface border border-tactical rounded-xl p-5 sm:p-7 flex flex-col gap-6 shadow-2xl max-w-4xl mx-auto print:border-none print:shadow-none print:p-0">
      {/* Top Header */}
      <div className="flex flex-wrap items-start justify-between gap-4 border-b border-tactical/70 pb-5">
        <div>
          <div className="flex items-center gap-2">
            <span className="font-mono text-xs font-bold text-amber-400 bg-amber-950/60 border border-amber-800/60 px-2.5 py-0.5 rounded">
              OFFICIAL MATCH PREPARATION DOSSIER
            </span>
            <span className="text-xs font-mono text-slate-400">
              {team.tournament}
            </span>
          </div>
          <h2 className="text-2xl font-black text-white mt-1 tracking-tight">
            Opposition Press Triggers: {team.name}
          </h2>
          <p className="text-xs text-slate-400 mt-1">
            Prescriptive tactical briefing prepared for coaching staff, defensive coordinators, and pressing unit leaders.
          </p>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-2 print:hidden">
          <button
            onClick={handleCopy}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg border text-xs font-medium transition-all ${
              copied
                ? 'bg-emerald-950/80 border-emerald-500 text-emerald-300'
                : 'bg-void border-tactical text-slate-300 hover:text-white hover:border-slate-500'
            }`}
          >
            {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? 'Brief Copied!' : 'Copy Tactical Brief'}</span>
          </button>

          <button
            onClick={handlePrint}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-tactical bg-void text-slate-300 hover:text-white hover:border-slate-500 text-xs font-medium transition-all"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Print Dossier</span>
          </button>
        </div>
      </div>

      {/* Metric Strip */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
        <div className="bg-panel p-3.5 rounded-lg border border-tactical/60 font-mono">
          <div className="text-[10px] text-slate-400 uppercase">Matches Sampled</div>
          <div className="text-xl font-bold text-white mt-0.5">{team.matchesPlayed} Matches</div>
          <div className="text-[10px] text-slate-400 font-sans">Full StatsBomb Event Logs</div>
        </div>

        <div className="bg-panel p-3.5 rounded-lg border border-tactical/60 font-mono">
          <div className="text-[10px] text-slate-400 uppercase">Lost Possession Rate</div>
          <div className="text-xl font-bold text-amber-400 mt-0.5">{team.turnoversPerMatch} / 90</div>
          <div className="text-[10px] text-slate-400 font-sans">{team.defensiveThirdTurnovers} in Def. Third</div>
        </div>

        <div className="bg-panel p-3.5 rounded-lg border border-tactical/60 font-mono">
          <div className="text-[10px] text-slate-400 uppercase">Press Escape Composure</div>
          <div className="text-xl font-bold text-emerald-400 mt-0.5">{team.overallPressEscapeRate}%</div>
          <div className="text-[10px] text-slate-400 font-sans">Under Direct Opposition Press</div>
        </div>

        <div className="bg-panel p-3.5 rounded-lg border border-tactical/60 font-mono">
          <div className="text-[10px] text-slate-400 uppercase">Transition Strike Window</div>
          <div className="text-xl font-bold text-crimson-400 mt-0.5">{team.avgTimeToConcededShotSec}s</div>
          <div className="text-[10px] text-slate-400 font-sans">Avg Time To Conceded Shot</div>
        </div>
      </div>

      {/* Triggers Section */}
      <div className="flex flex-col gap-4">
        <div className="flex items-center justify-between">
          <h3 className="text-sm font-bold uppercase tracking-wider text-slate-200 flex items-center gap-2">
            <ShieldAlert className="w-4 h-4 text-crimson-400" />
            Tactical Press Trigger Directives ({team.tacticalTriggers.length})
          </h3>
          <span className="text-xs font-mono text-slate-400">Order of Tactical Priority</span>
        </div>

        <div className="space-y-3.5">
          {team.tacticalTriggers.map((trigger, idx) => (
            <div
              key={trigger.id}
              className={`p-4 rounded-xl border flex flex-col sm:flex-row items-start gap-4 transition-all ${
                trigger.priority === 'CRITICAL'
                  ? 'bg-crimson-950/25 border-crimson-800/60'
                  : trigger.priority === 'HIGH'
                  ? 'bg-amber-950/25 border-amber-800/60'
                  : 'bg-panel border-tactical'
              }`}
            >
              {/* Priority badge */}
              <div className="flex-shrink-0 flex items-center gap-2 sm:flex-col sm:items-start sm:w-28">
                <span className={`px-2 py-0.5 rounded text-[10px] font-mono font-bold tracking-wider ${
                  trigger.priority === 'CRITICAL'
                    ? 'bg-crimson-900/80 text-crimson-300 border border-crimson-700'
                    : trigger.priority === 'HIGH'
                    ? 'bg-amber-900/80 text-amber-300 border border-amber-700'
                    : 'bg-slate-800 text-slate-300 border border-slate-700'
                }`}>
                  {trigger.priority}
                </span>
                <span className="text-[10px] font-mono text-slate-400">
                  TRIGGER #{idx + 1}
                </span>
              </div>

              {/* Main Instruction */}
              <div className="flex-grow space-y-1.5">
                <div className="flex flex-wrap items-center gap-2">
                  <h4 className="text-sm font-bold text-white">{trigger.title}</h4>
                  <span className="text-xs font-mono text-emerald-400 bg-emerald-950/60 px-2 py-0.5 rounded border border-emerald-800/50">
                    Zone {trigger.zoneId}
                  </span>
                </div>

                <p className="text-xs text-slate-200 leading-relaxed font-sans">
                  {trigger.instruction}
                </p>

                <div className="bg-void/80 p-2.5 rounded-lg border border-tactical/60 flex items-start gap-2 text-[11px] font-mono text-slate-300 mt-2">
                  <span className="text-amber-400 font-bold uppercase">Evidence Telemetry:</span>
                  <span>{trigger.evidenceStat}</span>
                </div>
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Transition Counter-Strike Framework */}
      <div className="bg-panel border border-tactical rounded-xl p-5 flex flex-col gap-3">
        <h4 className="text-xs font-bold uppercase tracking-wider text-slate-200 flex items-center gap-2">
          <Award className="w-4 h-4 text-emerald-400" />
          Rest-Defense Exploitation Guideline
        </h4>
        <p className="text-xs text-slate-300 leading-relaxed">
          When winning the ball in midfield from {team.name}, prioritize immediate vertical release into the half-spaces within the first <strong>{team.avgTimeToConcededShotSec} seconds</strong>. Their defensive transition structure takes approximately 8 seconds to reset into a compact block. Overcommitting to slow horizontal recirculation allows their press-resistant midfielders to recover defensive positioning.
        </p>
      </div>
    </div>
  );
};
